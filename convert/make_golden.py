import argparse
import json
import sys

import numpy as np
import torch

from helaai import (
    EOS_ID,
    MODELS,
    ROOT,
    load_reference_model,
    load_tokenizer,
    prompt_ids,
    reference_greedy,
    reference_namespace,
    store_path,
)

GOLDEN_DIR = ROOT / "golden"
PROMPTS_PATH = GOLDEN_DIR / "prompts.json"
REFERENCE_PATH = GOLDEN_DIR / "reference.json"
OUTPUTS_DOC_PATH = ROOT / "docs" / "model-outputs.md"
MAX_NEW_TOKENS = 40
TOP_K = 5
UNK_ID = 1
UNK_MARKER = "⟨UNK⟩"
ZWJ = "‍"
MODEL_ORDER = ("base", "it")

OUTPUTS_DOC_INTRO = """# Model Outputs on the Golden Prompts

This document lists every golden prompt together with the output of both SinhalaLM models, so
that the outputs can be read and validated by a native Sinhala speaker. It is generated by
`convert/make_golden.py` from `golden/reference.json`, and `make ci` fails if the two drift
apart.

### How the outputs were produced

- **Decoding** — greedy decoding with the original HelaAI reference implementation, up to
  {max_new_tokens} new tokens or until `<EOS>`.
- **Base model** — the model continues the prompt text, starting from `<BOS>`.
- **Instruct model** — the prompt is inserted as the question into the fine-tuning template
  below, starting from `<BOS>`.
- **Raw output** — the text exactly as the original `decode()` returns it, which drops `<UNK>`
  tokens. No ZWJ restoration and no HTML entity decoding are applied, since both are part of the
  application's post-processing.
- **With `<UNK>` shown** — the same output with each dropped `<UNK>` marked as {unk_marker}.
  This line appears only when the output contains `<UNK>`.

The instruct template, with `{{question}}` standing for the prompt:

```text
{template}
```
"""


def build_reference() -> tuple[dict, dict[str, np.ndarray]]:
    torch.manual_seed(0)
    prompts = json.loads(PROMPTS_PATH.read_text(encoding="utf-8"))["prompts"]
    tokenizer = load_tokenizer()
    cases, logits_by_key = [], {}
    for model in MODEL_ORDER:
        gpt = load_reference_model(model)
        for index, text in enumerate(prompts):
            ids = prompt_ids(model, text)
            with torch.no_grad():
                logits, _ = gpt(torch.tensor([ids]))
            greedy = reference_greedy(gpt, ids, MAX_NEW_TOKENS)
            key = f"p{index}_{model}"
            logits_by_key[key] = logits[0].numpy()
            cases.append(
                {
                    "key": key,
                    "model": model,
                    "prompt_index": index,
                    "prompt": text,
                    "input_ids": ids,
                    "input_tokens": [tokenizer.itos.get(i, "<UNK>") for i in ids],
                    "last_top_ids": logits[0, -1].topk(TOP_K).indices.tolist(),
                    "greedy_ids": greedy,
                    "greedy_text": tokenizer.decode(greedy),
                }
            )
    reference = {
        "sources": {
            name: {k: spec[k] for k in ("repo", "revision")} for name, spec in MODELS.items()
        },
        "max_new_tokens": MAX_NEW_TOKENS,
        "cases": cases,
    }
    return reference, logits_by_key


def plural(count: int, noun: str) -> str:
    return f"{count} {noun}" if count == 1 else f"{count} {noun}s"


def visible_unk_text(ids: list[int]) -> str:
    tokenizer = load_tokenizer()
    pieces = []
    for token_id in ids:
        token = tokenizer.itos.get(token_id, "<UNK>")
        if token_id == UNK_ID:
            pieces.append(UNK_MARKER)
        elif token not in ("<PAD>", "<BOS>", "<EOS>"):
            pieces.append(token)
    return "".join(pieces).replace("</w>", " ").strip()


def describe_output(case: dict) -> list[str]:
    ids = case["greedy_ids"]
    stop = "stopped at `<EOS>`" if ids and ids[-1] == EOS_ID else "stopped at the token limit"
    unk = ids.count(UNK_ID)
    lines = [
        f"{plural(len(ids), 'token')}, {stop}, {unk} `<UNK>`",
        "",
        f"> {case['greedy_text'] or '(empty)'}",
    ]
    if unk:
        lines += ["", "With `<UNK>` shown:", "", f"> {visible_unk_text(ids)}"]
    return lines


def render_outputs_doc(reference: dict) -> str:
    template = reference_namespace()["build_prompt"]("{question}").rstrip("\n")
    parts = [
        OUTPUTS_DOC_INTRO.format(
            max_new_tokens=reference["max_new_tokens"], unk_marker=UNK_MARKER, template=template
        )
    ]
    by_prompt: dict[int, dict[str, dict]] = {}
    for case in reference["cases"]:
        by_prompt.setdefault(case["prompt_index"], {})[case["model"]] = case
    for index in sorted(by_prompt):
        base, it = by_prompt[index]["base"], by_prompt[index]["it"]
        prompt = base["prompt"]
        notes = []
        if not prompt:
            notes.append("empty prompt, so the base model generates from `<BOS>` alone")
        if ZWJ in prompt:
            notes.append("contains a ZWJ, which the tokenizer maps to `<UNK>`")
        parts += [
            f"### Prompt {index + 1}",
            "",
            f"> {prompt or '(empty)'}",
            "",
            f"Input length: {plural(len(base['input_ids']), 'token')} for the base model, "
            f"{plural(len(it['input_ids']), 'token')} for the instruct model."
            + (f" Note: {'; '.join(notes)}." if notes else ""),
            "",
            "#### Base model",
            "",
            *describe_output(base),
            "",
            "#### Instruct model",
            "",
            *describe_output(it),
            "",
        ]
    return "\n".join(parts).rstrip("\n") + "\n"


def dump(reference: dict) -> str:
    return json.dumps(reference, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate golden reference outputs.")
    parser.add_argument("--check", action="store_true", help="fail if outputs differ")
    args = parser.parse_args()

    reference, logits = build_reference()
    expected = {REFERENCE_PATH: dump(reference), OUTPUTS_DOC_PATH: render_outputs_doc(reference)}

    if args.check:
        stale = [
            path
            for path, text in expected.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date", file=sys.stderr)
        if stale:
            return 1
        print("golden outputs are up to date")
    else:
        for path, text in expected.items():
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    logits_dir = store_path("golden")
    logits_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(logits_dir / "reference_logits.npz", **logits)
    return 0


if __name__ == "__main__":
    sys.exit(main())
