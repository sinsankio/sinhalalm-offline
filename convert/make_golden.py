import argparse
import json
import sys

import numpy as np
import torch
import transformers
from transformers import AutoModelForCausalLM, AutoTokenizer

from sinhalallm import (
    GOLDEN_PATH,
    PROMPTS_PATH,
    REPO,
    REVISION,
    ROOT,
    STOP_IDS,
    model_dir,
    store_path,
)

OUTPUTS_DOC_PATH = ROOT / "docs" / "model-outputs.md"
MAX_NEW_TOKENS = 64
TOP_K = 5
RANDOM_SEQ_LEN = 1024
RANDOM_STRIDE = 16
RANDOM_SEED = 0
FIRST_REGULAR_ID = 3

OUTPUTS_DOC_INTRO = """# SinhalaLLM-1.7B Outputs on the Golden Questions

This document lists every golden question together with the answer of SinhalaLLM-1.7B, so that
the answers can be read and validated by a native Sinhala speaker. It is generated by
`convert/make_golden.py` from `golden/reference.json`, and `make check-golden` fails if the two
drift apart.

### How the answers were produced

- **Model** — `{repo}` at revision `{revision}`, loaded in fp32 with `transformers`
  {transformers_version}, the version the model was saved with.
- **Prompt** — the question as written in `golden/prompts.json`, wrapped in the model's ChatML
  template. No ZWJ repair is applied, since the repair belongs to the application.
- **Decoding** — greedy decoding, up to {max_new_tokens} new tokens or until `<|im_end|>` or
  `<|endoftext|>`.
- **Answer** — the decoded text without special tokens. No HTML entity decoding is applied.
"""


def load_reference():
    path = model_dir()
    tokenizer = AutoTokenizer.from_pretrained(path)
    model = AutoModelForCausalLM.from_pretrained(path, dtype=torch.float32).eval()
    rope_theta = model.config.rope_parameters["rope_theta"]
    if rope_theta != 130000:
        raise AssertionError(f"reference rope_theta is {rope_theta}, expected 130000")
    return tokenizer, model


def chat_prompt(tokenizer, question: str) -> str:
    messages = [{"role": "user", "content": question}]
    return tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)


@torch.no_grad()
def build_reference() -> tuple[dict, dict[str, np.ndarray]]:
    torch.manual_seed(0)
    tokenizer, model = load_reference()
    questions = json.loads(PROMPTS_PATH.read_text(encoding="utf-8"))["questions"]
    cases, logits_by_key = [], {}
    for index, question in enumerate(questions):
        prompt = chat_prompt(tokenizer, question)
        ids = tokenizer(prompt, add_special_tokens=False)["input_ids"]
        batch = torch.tensor([ids])
        logits = model(batch).logits[0]
        output = model.generate(
            batch,
            attention_mask=torch.ones_like(batch),
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=False,
            eos_token_id=STOP_IDS,
            pad_token_id=STOP_IDS[1],
        )
        greedy = output[0, len(ids) :].tolist()
        key = f"q{index + 1}"
        logits_by_key[key] = logits.numpy()
        cases.append(
            {
                "key": key,
                "question": question,
                "prompt": prompt,
                "input_ids": ids,
                "last_top_ids": logits[-1].topk(TOP_K).indices.tolist(),
                "greedy_ids": greedy,
                "answer": tokenizer.decode(greedy, skip_special_tokens=True).strip(),
            }
        )

    generator = torch.Generator().manual_seed(RANDOM_SEED)
    vocab = len(tokenizer)
    random_ids = torch.randint(FIRST_REGULAR_ID, vocab, (RANDOM_SEQ_LEN,), generator=generator)
    positions = list(range(RANDOM_STRIDE - 1, RANDOM_SEQ_LEN, RANDOM_STRIDE))
    logits_by_key["random"] = model(random_ids[None]).logits[0, positions].numpy()

    reference = {
        "source": {
            "repo": REPO,
            "revision": REVISION,
            "transformers": transformers.__version__,
        },
        "max_new_tokens": MAX_NEW_TOKENS,
        "random": {
            "seed": RANDOM_SEED,
            "length": RANDOM_SEQ_LEN,
            "low": FIRST_REGULAR_ID,
            "high": vocab,
            "positions": positions,
        },
        "cases": cases,
    }
    return reference, logits_by_key


def render_outputs_doc(reference: dict) -> str:
    source = reference["source"]
    parts = [
        OUTPUTS_DOC_INTRO.format(
            repo=source["repo"],
            revision=source["revision"],
            transformers_version=source["transformers"],
            max_new_tokens=reference["max_new_tokens"],
        )
    ]
    for case in reference["cases"]:
        ids = case["greedy_ids"]
        stopped = "stopped by itself" if ids and ids[-1] in STOP_IDS else "cut at the token limit"
        parts += [
            f"### {case['key'].upper()}. {case['question']}",
            "",
            f"{len(case['input_ids'])} prompt tokens, {len(ids)} answer tokens, {stopped}.",
            "",
            f"> {' '.join(case['answer'].split()) or '(empty)'}",
            "",
        ]
    return "\n".join(parts).rstrip("\n") + "\n"


def dump(reference: dict) -> str:
    return json.dumps(reference, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate golden reference outputs.")
    parser.add_argument("--check", action="store_true", help="fail if outputs differ")
    args = parser.parse_args()

    reference, logits = build_reference()
    expected = {GOLDEN_PATH: dump(reference), OUTPUTS_DOC_PATH: render_outputs_doc(reference)}

    if args.check:
        stale = [
            p for p, text in expected.items() if not p.exists() or p.read_text("utf-8") != text
        ]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date", file=sys.stderr)
        if stale:
            return 1
        print("golden outputs are up to date")
    else:
        for path, text in expected.items():
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    logits_dir = store_path("golden")
    logits_dir.mkdir(parents=True, exist_ok=True)
    np.savez(logits_dir / "reference_logits.npz", **logits)
    return 0


if __name__ == "__main__":
    sys.exit(main())
